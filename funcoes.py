def exibir_menu():
    print("=== menu do programa ===")
    print("[1] - somar")
    print("[2] - subtrair")
    print("[3] - multiplicar")
    print("[4] - dividir")

def somar(numero1,numero2):
    resultado = numero1 + numero2
    return resultado

def subtrair(numero1,numero2):
    resultado = numero1 - numero2
    return resultado

def multiplicar(numero1,numero2):
    resultado = numero1 * numero2
    return resultado


def dividir(numero1,numero2):
    resultado = numero1 / numero2
    return resultado

